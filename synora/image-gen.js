(() => {
  const form = document.getElementById('chatForm');
  const input = document.getElementById('chatInput');
  const messages = document.getElementById('chatMessages');
  const send = document.getElementById('chatSend');
  const notice = document.getElementById('chatNotice');
  if (!form || !input || !messages || !send) return;

  const imageIntent = /(image|photo|picture|portrait|wallpaper|illustration|draw|paint|generate.*(image|photo|picture)|create.*(image|photo|picture)|make.*(image|photo|picture)|ছবি|ফটো|চিত্র|আঁকো|আঁকা|ছবি বানাও|ছবি তৈরি|ফটো বানাও|ছবি দাও|একটা ছবি|একটি ছবি|तस्वीर|फोटो|चित्र|बनाओ|तस्वीर बनाओ|फोटो बनाओ|imagen|foto|dibuja|crée.*image)/i;

  const backgroundIntent = /(background|back\s*ground|ব্যাকগ্রাউন্ড|পেছনের দৃশ্য|পটভূমি|पृष्ठभूमि|फोटो का बैकग्राउंड|fondo)/i;
  const editIntent = /(সুন্দর করো|আরও সুন্দর|সাজাও|পরিবর্তন করো|বদলে দাও|মুছে দাও|যোগ করো|রং বদলাও|লাইট ঠিক|চেঞ্জ করো|edit|make it|improve|enhance|change|replace|remove|add|retouch|background change|cambiar|mejora|editar)/i;
  let lastGeneratedImage = "";

  function makeImagePrompt(original) {
    const p = original.toLowerCase();
    // FLUX Schnell follows concise English subject descriptions more reliably
    // than short Bengali/Hindi requests. Keep the user's requested subject first.
    if (/(শাড়ি|শাড়ি|saree|sari|साड़ी)/i.test(p)) {
      return "Create exactly this subject: a respectful, photorealistic full-length portrait of an adult South Asian woman wearing an elegant traditional saree. Show the saree clearly, including its drape and fabric, with a natural graceful pose and a simple tasteful background. The woman in the saree must be the central subject. Do not create a landscape or unrelated scene. User request: " + original;
    }
    if (/(শুধু মেয়ে|শুধু মেয়ে|only girl|only woman|plain background|সাদা ব্যাকগ্রাউন্ড)/i.test(p)) {
      return "Create exactly this subject: a respectful, photorealistic head-and-shoulders portrait of an adult South Asian woman alone against a plain clean neutral studio background. No other people, objects, scenery, or distracting background. User request: " + original;
    }
    if (/(মেয়ে|মেয়ের|মহিলা|নারী|স্ত্রী|woman|women|girl|female|ladki|mahila|mujer)/i.test(p)) {
      return "Create exactly this subject: a respectful, photorealistic head-and-shoulders portrait of an adult South Asian woman, looking toward the camera, natural expression, tasteful everyday clothing, softly lit uncluttered background. The woman must be clearly visible and be the main subject. Do not create a landscape, mountains, buildings, or an unrelated scene. User request: " + original;
    }
    if (/(গোলাপ|ফুল|ফুলের|rose|flower|फूल|गुलाब|flor|rosa)/i.test(p)) {
      return "Create exactly this subject: a beautiful close-up photograph of a single fresh rose flower in full bloom, clearly visible petals, natural botanical detail, soft daylight, simple softly blurred garden background. The flower must fill most of the frame. Do not create people, mountains, buildings, or an unrelated landscape. User request: " + original;
    }
    if (/(বিড়াল|বিড়াল|cat|kitten|बिल्ली|gato)/i.test(p)) {
      return "Create exactly this subject: a clear, charming photorealistic close-up of a cat, with the cat as the central subject and a simple background. Do not create a landscape or unrelated subject. User request: " + original;
    }
    if (/(কুকুর|dog|puppy|कुत्ता|perro)/i.test(p)) {
      return "Create exactly this subject: a clear, charming photorealistic image of a dog, with the dog as the central subject and a simple background. Do not create a landscape or unrelated subject. User request: " + original;
    }
    return "Create an image that depicts exactly the subject and scene requested here. Make the main requested subject large, clear, and central. Do not substitute a landscape or unrelated subject. Request: " + original;
  }

  function bubble(text) {
    const node = document.createElement('div');
    node.className = 'chat-bubble assistant-bubble';
    node.textContent = text;
    messages.append(node);
    messages.scrollTop = messages.scrollHeight;
  }

  function showGeneratedImage(dataUrl) {
    const card = document.createElement('figure');
    card.className = 'chat-bubble assistant-bubble';
    card.style.padding = '10px';
    card.style.maxWidth = 'min(100%, 520px)';
    const image = document.createElement('img');
    image.src = dataUrl;
    image.alt = 'Image generated by SYNORA AI';
    image.loading = 'lazy';
    image.style.display = 'block';
    image.style.width = '100%';
    image.style.height = 'auto';
    image.style.borderRadius = '12px';
    const actions = document.createElement('div');
    actions.style.display = 'flex';
    actions.style.justifyContent = 'flex-end';
    actions.style.paddingTop = '10px';
    const download = document.createElement('a');
    download.href = dataUrl;
    download.download = 'synora-generated-image.jpg';
    download.textContent = 'Download image ↓';
    download.className = 'text-btn';
    download.style.textDecoration = 'none';
    actions.append(download);
    card.append(image, actions);
    messages.append(card);
    messages.scrollTop = messages.scrollHeight;
  }

  // Capture the chat form before the normal text-chat handler. Requests with an
  // attached photo continue through the existing image-edit flow instead.
  document.addEventListener('submit', async (event) => {
    if (event.target !== form) return;
    const prompt = input.value.trim();
    const attachedImage = document.getElementById('chatImage');
    if (prompt && backgroundIntent.test(prompt) && !(attachedImage && attachedImage.files && attachedImage.files.length) && !lastGeneratedImage) {
      event.preventDefault();
      event.stopImmediatePropagation();
      const user = document.createElement('div');
      user.className = 'chat-bubble user-bubble';
      user.textContent = prompt;
      messages.append(user);
      bubble('Please attach the photo you want to edit using the + button, then tell me the background you want (for example: garden, beach, mountains, or city). I will edit the uploaded photo rather than create a new unrelated image.');
      input.value = '';
      messages.scrollTop = messages.scrollHeight;
      return;
    }
    if (!prompt || (attachedImage && attachedImage.files && attachedImage.files.length)) return;

    // Treat short follow-up instructions as edits to the most recently generated image.
    if (lastGeneratedImage && editIntent.test(prompt)) {
      event.preventDefault();
      event.stopImmediatePropagation();
      if (send.disabled) return;
      const user = document.createElement('div');
      user.className = 'chat-bubble user-bubble';
      user.textContent = prompt;
      messages.append(user);
      input.value = '';
      send.disabled = true;
      send.textContent = 'Editing…';
      if (notice) {
        notice.hidden = false;
        notice.textContent = 'SYNORA is editing your previous image…';
      }
      try {
        const response = await fetch('/api/image-edit', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            image: lastGeneratedImage,
            prompt: "Edit the supplied image according to this exact user instruction: " + prompt + ". Preserve the original main subject, identity, pose, clothing, and composition unless the user explicitly asks to change them. Do not replace the subject with an unrelated scene. Return only the edited image."
          })
        });
        const result = await response.json().catch(() => ({}));
        if (!response.ok) throw new Error(result.error || 'Image editing failed.');
        if (typeof result.image !== 'string' || !result.image.startsWith('data:image/')) {
          throw new Error('The image editor returned no image.');
        }
        lastGeneratedImage = result.image;
        bubble('Your edited image is ready.');
        showGeneratedImage(result.image);
        if (notice) notice.hidden = true;
      } catch (error) {
        bubble('I could not edit the image. ' + (error.message || 'Please try again.'));
        if (notice) {
          notice.hidden = false;
          notice.textContent = error.message || 'Image editing failed.';
        }
        input.value = prompt;
      } finally {
        send.disabled = false;
        send.textContent = 'Send ↗';
        input.focus();
      }
      return;
    }

    if (!imageIntent.test(prompt)) return;

    event.preventDefault();
    event.stopImmediatePropagation();
    if (send.disabled) return;

    const user = document.createElement('div');
    user.className = 'chat-bubble user-bubble';
    user.textContent = prompt;
    messages.append(user);
    input.value = '';
    send.disabled = true;
    send.textContent = 'Creating…';
    if (notice) {
      notice.hidden = false;
      notice.textContent = 'SYNORA is creating your image…';
    }

    try {
      const response = await fetch('/api/image-generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ prompt: makeImagePrompt(prompt) })
      });
      const result = await response.json().catch(() => ({}));
      if (!response.ok) throw new Error(result.error || 'Image generation failed.');
      if (typeof result.image !== 'string' || !result.image.startsWith('data:image/')) {
        throw new Error('The image service returned no image.');
      }
      lastGeneratedImage = result.image;
      bubble('Your image is ready.');
      showGeneratedImage(result.image);
      if (notice) notice.hidden = true;
    } catch (error) {
      bubble('I could not create that image. ' + (error.message || 'Please try again.'));
      if (notice) {
        notice.hidden = false;
        notice.textContent = error.message || 'Image generation failed.';
      }
      input.value = prompt;
    } finally {
      send.disabled = false;
      send.textContent = 'Send ↗';
      input.focus();
    }
  }, true);
})();
